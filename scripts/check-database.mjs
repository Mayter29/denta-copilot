import { spawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { checkConcurrency } from './database-concurrency.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const container = 'denta-copilot-db-' + randomUUID();
// Official PostgreSQL 17.11, pinned to the image inspected when designing this proposal.
const image = 'postgres@sha256:b0f9560a2de083e2cc7382e75f808c7381a32852a7ec49117deedb300e552b24';
function docker(args, input = '', onOutput = () => {}) {
  return new Promise((resolve, reject) => {
    const child = spawn('docker', args, {
      shell: false,
      windowsHide: true,
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    let stdout = '',
      stderr = '';
    const timer = setTimeout(() => {
      child.kill();
      reject(new Error('Docker operation timed out'));
    }, 60_000);
    child.stdout.on('data', (data) => {
      stdout += data;
      onOutput(stdout);
    });
    child.stderr.on('data', (data) => {
      stderr += data;
    });
    child.on('error', (error) => {
      clearTimeout(timer);
      reject(error);
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ code, stdout, stderr });
    });
    child.stdin.on('error', () => {});
    child.stdin.end(input);
  });
}
function sql(text, onOutput) {
  return docker(
    [
      'exec',
      '-i',
      container,
      'psql',
      '-h',
      '127.0.0.1',
      '-X',
      '-q',
      '-A',
      '-t',
      '-v',
      'ON_ERROR_STOP=1',
      '-v',
      'VERBOSITY=verbose',
      '-U',
      'postgres',
      '-d',
      'denta_test',
    ],
    text,
    onOutput,
  );
}
function requireSuccess(result, label) {
  if (result.code !== 0) throw new Error(label + ': ' + result.stderr);
  return result.stdout.trim();
}
async function file(name) {
  return readFile(path.join(root, name), 'utf8');
}
try {
  requireSuccess(
    await docker([
      'run',
      '--detach',
      '--rm',
      '--network',
      'none',
      '--name',
      container,
      '--memory',
      '512m',
      '--tmpfs',
      '/var/lib/postgresql/data:rw,noexec,nosuid,size=256m',
      '--env',
      'POSTGRES_HOST_AUTH_METHOD=trust',
      '--env',
      'POSTGRES_DB=denta_test',
      image,
    ]),
    'start local test DB',
  );
  let ready = false;
  for (let attempt = 0; attempt < 60; attempt++) {
    if (
      (
        await docker([
          'exec',
          container,
          'pg_isready',
          '-h',
          '127.0.0.1',
          '-U',
          'postgres',
          '-d',
          'denta_test',
        ])
      ).code === 0
    ) {
      ready = true;
      break;
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  if (!ready) throw new Error('Local database did not become ready');
  const names = (await readdir(path.join(root, 'supabase/migrations')))
    .filter((name) => /^\d{14}_.+\.sql$/.test(name))
    .sort();
  if (names.length === 0) throw new Error('No versioned database migrations found');
  const parts = await Promise.all(names.map((name) => file('supabase/migrations/' + name)));
  requireSuccess(
    await sql(
      'begin;\n' +
        (await file('supabase/tests/bootstrap.sql')) +
        '\n' +
        parts.join('\n') +
        '\ncommit;',
    ),
    'versioned schema',
  );
  console.log(
    'PostgreSQL migrations applied to isolated local database (' + names.length + ' SQL files).',
  );
  const demoSeed = await file('supabase/seeds/demo-secretaria.sql');
  const demoMembership = (await file('supabase/seeds/grant-membership.sql')).replaceAll(
    '<AUTH_USER_UUID>',
    '00000000-0000-4000-8000-000000000001',
  );
  const seeded = requireSuccess(
    await sql(
      "begin;\ninsert into auth.users(id) values ('00000000-0000-4000-8000-000000000001');\n" +
        demoSeed +
        '\n' +
        demoMembership +
        '\n' +
        (await file('supabase/tests/demo-seed.sql')) +
        '\nrollback;',
    ),
    'controlled demo seed',
  );
  console.log(
    seeded
      .split('\n')
      .filter((line) => line.endsWith('_ok'))
      .join('\n'),
  );
  requireSuccess(
    await sql('begin;\n' + (await file('supabase/tests/fixtures.sql')) + '\ncommit;'),
    'isolated invariant fixtures',
  );
  for (const name of ['invariants.sql', 'decisions.sql']) {
    const output = requireSuccess(await sql(await file('supabase/tests/' + name)), name);
    console.log(
      output
        .split('\n')
        .filter((line) => line.endsWith('_ok'))
        .join('\n'),
    );
  }
  requireSuccess(await sql(await file('supabase/tests/concurrency.sql')), 'concurrency fixtures');
  await checkConcurrency(sql, requireSuccess);
} finally {
  // Exact UUID name generated by this process; never touches existing containers or host folders.
  if (!/^denta-copilot-db-[0-9a-f-]{36}$/.test(container))
    throw new Error('Invalid test container name');
  await docker(['rm', '--force', container]);
}
